#!/usr/bin/env python3
"""Builds the level table for AFTERIMAGE (32x18 tiles) and prints a JS module."""
W, H = 32, 18


class Grid:
    def __init__(self):
        self.g = [['.'] * W for _ in range(H)]

    def rect(self, x0, y0, x1, y1, ch='#'):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if 0 <= x < W and 0 <= y < H:
                    self.g[y][x] = ch

    def put(self, x, y, ch):
        self.g[y][x] = ch

    def rows(self):
        return [''.join(r) for r in self.g]


def base(floor_y=15):
    g = Grid()
    g.rect(0, floor_y, W - 1, H - 1, '#')
    return g


levels = []


def add(name, chapter, g, spawn, goal, hint, par, max_echoes=None, palette=0):
    g.put(spawn[0], spawn[1], 'p')
    g.put(goal[0], goal[1], 'o')
    levels.append(dict(name=name, chapter=chapter, map=g.rows(), hint=hint, par=par,
                       maxEchoes=max_echoes if max_echoes is not None else par,
                       palette=palette))


# ---------------------------------------------------------------- chapter 1
# 1. First Light — a pit you cannot clear; your failed run becomes the stone.
g = base()
g.rect(9, 15, 16, 17, '.')     # pit
g.rect(9, 16, 16, 16, '^')     # spikes at the bottom of the pit
add('First Light', 0, g, spawn=(3, 14), goal=(24, 14),
    hint='You cannot clear this gap. Your past self can.', par=1, palette=0)

# 2. Air Step — hold yourself in the air at the top of a jump.
g = base()
g.rect(16, 11, 24, 11, "#")    # a floating shelf, four tiles out of reach
add('Air Step', 0, g, spawn=(3, 14), goal=(20, 10),
    hint='Let go of the run in mid-air. Leave yourself a step.', par=1, palette=0)

# ---------------------------------------------------------------- chapter 2
# 3. Hold — an echo can stand on a plate while you walk through the door.
g = base()
g.rect(18, 9, 18, 14, 'D')     # door column
g.rect(18, 9, 18, 9, '#')
g.put(7, 14, 'P')
g.rect(18, 8, 30, 8, '#')
add('Hold', 1, g, spawn=(3, 14), goal=(25, 14),
    hint='A door needs weight. Weight can be left behind.', par=1, palette=1)

# 4. Two Voices — both plates at once, one on the ground, one on a step.
g = base()
g.rect(22, 8, 22, 14, 'D')
g.rect(12, 13, 15, 17, '#')     # two-tile step, reachable in one jump
g.put(6, 14, 'P')
g.put(13, 12, 'P')
add('Two Voices', 1, g, spawn=(2, 14), goal=(27, 14),
    hint='Two plates hold one door. You only own one body at a time.', par=2, palette=1)

# 5. Chimney — one shaft, no ledges: you stack yourself upward.
g = base()
g.rect(13, 2, 13, 10, '#')      # left wall of the shaft
g.rect(16, 2, 16, 14, '#')      # right wall
g.rect(13, 2, 16, 2, '#')       # ceiling
add('Chimney', 1, g, spawn=(3, 14), goal=(14, 4),
    hint='No ledges. Stack yourself, one jump at a time.', par=2, palette=1)

# ---------------------------------------------------------------- chapter 3
# 6. Switchback — spikes below, a gate above, and a narrow landing.
g = base()
g.rect(6, 15, 15, 17, '.')
g.rect(6, 16, 15, 16, '^')
g.rect(9, 11, 16, 14, '#')      # mid shelf
g.rect(19, 7, 26, 10, '#')      # high shelf with the gate
g.rect(22, 11, 22, 13, 'D')
g.put(12, 10, 'P')
add('Switchback', 2, g, spawn=(2, 14), goal=(28, 9),
    hint='Up, across, and through. Two of you will be needed.', par=2, palette=2)

if __name__ == '__main__':
    import io
    out = io.StringIO()
    out.write('/* Level table for AFTERIMAGE — generated by tools/mklevels.py */\n')
    out.write('export const LEVELS = [\n')
    for i, lv in enumerate(levels):
        out.write('  {\n')
        out.write(f'    name: {lv["name"]!r},\n'.replace('"', "'"))
        out.write(f'    chapter: {lv["chapter"]},\n')
        out.write(f'    par: {lv["par"]},\n')
        out.write(f'    maxEchoes: {lv["maxEchoes"]},\n')
        out.write(f'    palette: {lv["palette"]},\n')
        out.write(f'    hint: {lv["hint"]!r},\n'.replace('"', "'"))
        out.write('    map: [\n')
        for r in lv['map']:
            out.write(f"      '{r}',\n")
        out.write('    ],\n  },\n')
    out.write('];\n')
    open('build/js/levels.js', 'w').write(out.getvalue())
    print('wrote build/js/levels.js', len(levels), 'levels')
